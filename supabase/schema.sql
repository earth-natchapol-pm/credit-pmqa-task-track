create table if not exists public.team_members (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null,
  focus_area text not null default 'Credit Platform',
  initials text not null,
  tone text not null default 'avatar-orange',
  created_at timestamptz not null default now()
);

alter table public.team_members enable row level security;

drop policy if exists "Allow public read access to team members" on public.team_members;
drop policy if exists "Allow public insert access to team members" on public.team_members;
drop policy if exists "Allow public update access to team members" on public.team_members;
drop policy if exists "Allow public delete access to team members" on public.team_members;

create policy "Allow public read access to team members"
  on public.team_members for select
  using (true);

