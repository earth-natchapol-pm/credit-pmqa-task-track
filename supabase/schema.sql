create table if not exists public.feature_products (
  feature_id bigint not null references public.features(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (feature_id, product_id)
);

insert into public.feature_products (feature_id, product_id)
select feature.id, product.id
from public.features feature
join public.products product on lower(product.name) = lower(feature.product)
on conflict (feature_id, product_id) do nothing;

